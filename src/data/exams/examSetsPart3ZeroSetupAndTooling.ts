import { ExamQuestion, ExamSet } from '../../types/assessment.types';
import { SkillLevel, StageId } from '../../types/curriculum.types';

function q(
  id: string,
  stageId: StageId,
  level: SkillLevel,
  category: string,
  tags: string[],
  question: string,
  codeSnippet: string | undefined,
  options: [string, string, string, string],
  why: [string, string, string, string],
  correctIdx: 0 | 1 | 2 | 3,
  overallExplanation: string,
  analogyReminder: string,
  relatedTermIds: string[] = []
): ExamQuestion {
  const ids = ['a', 'b', 'c', 'd'] as const;
  return {
    id,
    stageId,
    level,
    category,
    tags,
    question,
    ...(codeSnippet ? { codeSnippet } : {}),
    options: [0, 1, 2, 3].map((i) => ({
      id: ids[i],
      text: options[i],
      whyRightOrWrong: why[i],
    })),
    correctOptionId: ids[correctIdx],
    overallExplanation,
    analogyReminder,
    relatedTermIds,
  };
}

